WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  l_account_count PLS_INTEGER;
  l_object_count  PLS_INTEGER;
BEGIN
  SELECT COUNT(*)
    INTO l_account_count
    FROM USER_TABLES
   WHERE TABLE_NAME = 'BEX_ACCOUNT';

  IF l_account_count <> 1 THEN
    RAISE_APPLICATION_ERROR(
      -20001,
      'BEX_ACCOUNT must exist before BEX_ACCOUNT_IDENTITY is created'
    );
  END IF;

  SELECT COUNT(*)
    INTO l_object_count
    FROM USER_OBJECTS
   WHERE OBJECT_NAME = 'BEX_ACCOUNT_IDENTITY';

  IF l_object_count > 0 THEN
    RAISE_APPLICATION_ERROR(
      -20002,
      'BEX_ACCOUNT_IDENTITY already exists or conflicts with an object'
    );
  END IF;
END;
/

ALTER TABLE BEX_ACCOUNT MODIFY ACC_PASSWORD_HASH NULL;

COMMENT ON COLUMN BEX_ACCOUNT.ACC_PASSWORD_HASH IS
  'Optional local password credential; null for social-only accounts';

CREATE TABLE BEX_ACCOUNT_IDENTITY
(
  AID_ID               NUMBER
                       GENERATED ALWAYS AS IDENTITY
                       (
                         START WITH 1
                         INCREMENT BY 1
                         CACHE 20
                         NOCYCLE
                       ),
  AID_PUBLIC_ID        CHAR(32 CHAR) NOT NULL,
  ACC_ID               NUMBER NOT NULL,
  AID_PROVIDER         VARCHAR2(20 CHAR) NOT NULL,
  AID_ISSUER           VARCHAR2(500 CHAR) NOT NULL,
  AID_SUBJECT          VARCHAR2(255 CHAR) NOT NULL,
  AID_EMAIL            VARCHAR2(255 CHAR),
  AID_EMAIL_VERIFIED   CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
  AID_STATUS           VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
  AID_LINKED_AT        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  AID_LAST_LOGIN_AT    TIMESTAMP(6),
  AID_UNLINKED_AT      TIMESTAMP(6),
  AID_CREATED_AT       TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  AID_UPDATED_AT       TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  AID_CREATED_BY       NUMBER,
  AID_UPDATED_BY       NUMBER,
  CONSTRAINT PK_AID
    PRIMARY KEY (AID_ID),
  CONSTRAINT UK_AID_PUBLIC_ID
    UNIQUE (AID_PUBLIC_ID),
  CONSTRAINT UK_AID_PROVIDER_SUBJECT
    UNIQUE (AID_PROVIDER, AID_ISSUER, AID_SUBJECT),
  CONSTRAINT UK_AID_ACCOUNT_PROVIDER
    UNIQUE (ACC_ID, AID_PROVIDER),
  CONSTRAINT FK_AID_ACCOUNT
    FOREIGN KEY (ACC_ID)
    REFERENCES BEX_ACCOUNT (ACC_ID),
  CONSTRAINT CK_AID_PROVIDER
    CHECK (AID_PROVIDER IN ('GOOGLE', 'APPLE', 'FACEBOOK')),
  CONSTRAINT CK_AID_EMAIL_VERIFIED
    CHECK (AID_EMAIL_VERIFIED IN ('Y', 'N')),
  CONSTRAINT CK_AID_STATUS
    CHECK (AID_STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX IDX_AID_ACCOUNT
  ON BEX_ACCOUNT_IDENTITY (ACC_ID);

CREATE INDEX IDX_AID_STATUS
  ON BEX_ACCOUNT_IDENTITY (AID_STATUS);

COMMENT ON TABLE BEX_ACCOUNT_IDENTITY IS
  'Verified external authentication identities linked to an account';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_PUBLIC_ID IS
  'Immutable public identifier generated by the application';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.ACC_ID IS
  'Internal account that owns the external identity';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_PROVIDER IS
  'Approved external provider code';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_ISSUER IS
  'Verified token issuer';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_SUBJECT IS
  'Stable provider subject; never replaced by email';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_EMAIL IS
  'Last normalized email observed in verified provider claims';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_EMAIL_VERIFIED IS
  'Whether the provider verified the observed email';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_STATUS IS
  'ACTIVE or logically unlinked INACTIVE identity';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_LINKED_AT IS
  'Timestamp of the most recent successful link';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_LAST_LOGIN_AT IS
  'Timestamp of the most recent successful social login';
COMMENT ON COLUMN BEX_ACCOUNT_IDENTITY.AID_UNLINKED_AT IS
  'Timestamp of logical unlinking';
